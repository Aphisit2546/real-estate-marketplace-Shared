// Regenerates supabase/seed-locations.sql from the MIT-licensed kongvut/thai-province-data.
// Usage: node scripts/generate-locations-seed.mjs <folder with district.json and sub_district.json>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [source] = process.argv.slice(2);
if (!source) throw new Error('Pass the folder that holds district.json and sub_district.json');

const read = (name) => JSON.parse(readFileSync(join(source, name), 'utf8')).filter((row) => !row.deleted_at);
const text = (value) => `'${String(value).trim().replaceAll("'", "''")}'`;

const districts = read('district.json');
const subdistricts = read('sub_district.json');
const districtIds = new Set(districts.map((row) => row.id));

const districtRows = districts.map((row) => {
  const code = String(row.id);
  return `  (${text(code)}, ${text(code.slice(0, 2))}, ${text(row.name.th)}, ${text(row.name.en)})`;
});

const subdistrictRows = subdistricts.map((row) => {
  if (!districtIds.has(row.district_id)) throw new Error(`Unknown district ${row.district_id}`);
  const postal = /^\d{5}$/.test(String(row.zip_code)) ? text(row.zip_code) : 'null';
  return `  (${text(row.id)}, ${text(row.district_id)}, ${text(row.name.th)}, ${text(row.name.en)}, ${postal})`;
});

const sql = `-- Generated by scripts/generate-locations-seed.mjs. Do not edit by hand.
-- Source: github.com/kongvut/thai-province-data (MIT). Runs after seed.sql, which holds the provinces.
-- Codes follow the Thai administrative numbering, so re-running updates names in place.

insert into public.locations (code, level, parent_id, name_th, name_en)
select v.code, 'district'::public.location_level, p.id, v.name_th, v.name_en
from (values
${districtRows.join(',\n')}
) as v (code, province_code, name_th, name_en)
join public.locations p on p.code = v.province_code and p.level = 'province'
on conflict (code) do update set name_th = excluded.name_th, name_en = excluded.name_en;

insert into public.locations (code, level, parent_id, name_th, name_en, postal_code)
select v.code, 'subdistrict'::public.location_level, d.id, v.name_th, v.name_en, v.postal_code
from (values
${subdistrictRows.join(',\n')}
) as v (code, district_code, name_th, name_en, postal_code)
join public.locations d on d.code = v.district_code and d.level = 'district'
on conflict (code) do update
  set name_th = excluded.name_th, name_en = excluded.name_en, postal_code = excluded.postal_code;
`;

writeFileSync(new URL('../supabase/seed-locations.sql', import.meta.url), sql);
console.info(`${districts.length} districts, ${subdistricts.length} subdistricts`);
