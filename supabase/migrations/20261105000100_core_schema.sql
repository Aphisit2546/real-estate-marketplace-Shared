-- ---------------------------------------------------------------- property hierarchy
-- A project may contain buildings (parent_id). 'standalone' is created implicitly
-- for a listing that does not belong to any named project.
create table public.properties (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid references public.properties (id) on delete restrict,
  kind public.property_kind not null,
  name_th text not null check (char_length(name_th) between 1 and 200),
  name_en text check (char_length(name_en) <= 200),
  developer text check (char_length(developer) <= 200),
  address text not null check (char_length(address) between 1 and 500),
  province_id integer not null references public.locations (id) on delete restrict,
  district_id integer not null references public.locations (id) on delete restrict,
  subdistrict_id integer references public.locations (id) on delete restrict,
  postal_code text check (postal_code ~ '^[0-9]{5}$'),
  -- Coordinates are limited to Thailand's bounding box.
  lat numeric(9, 6) check (lat between 5 and 21),
  lng numeric(9, 6) check (lng between 97 and 106),
  total_floors integer check (total_floors between 1 and 200),
  year_built integer check (year_built between 1900 and 2100),
  created_by uuid not null references public.profiles (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((lat is null) = (lng is null)),
  check (parent_id is null or parent_id <> id)
);
create index properties_parent_idx on public.properties (parent_id);
create index properties_location_idx on public.properties (province_id, district_id, subdistrict_id);
create index properties_district_idx on public.properties (district_id);
create index properties_subdistrict_idx on public.properties (subdistrict_id);
create index properties_created_by_idx on public.properties (created_by);
create index properties_geo_idx on public.properties (lat, lng) where lat is not null;
create index properties_name_trgm_idx on public.properties using gin (name_th extensions.gin_trgm_ops);
create trigger properties_updated_at before update on public.properties
  for each row execute function public.set_updated_at();

create table public.property_amenities (
  property_id uuid not null references public.properties (id) on delete cascade,
  amenity_id integer not null references public.amenities (id) on delete restrict,
  primary key (property_id, amenity_id)
);
create index property_amenities_amenity_idx on public.property_amenities (amenity_id);

create table public.property_units (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties (id) on delete restrict,
  owner_id uuid not null references public.profiles (id) on delete restrict,
  unit_number text check (char_length(unit_number) between 1 and 50),
  floor integer check (floor between -5 and 200),
  area_sqm numeric(8, 2) not null check (area_sqm > 0 and area_sqm < 100000),
  bedrooms smallint not null default 0 check (bedrooms between 0 and 50),
  bathrooms smallint not null default 1 check (bathrooms between 0 and 50),
  parking_spaces smallint not null default 0 check (parking_spaces between 0 and 50),
  furnishing public.furnishing_level not null default 'unfurnished',
  appliances text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- Several agents may legitimately market the same physical room, so uniqueness is per owner.
create unique index property_units_owner_number_key on public.property_units (property_id, owner_id, unit_number)
  where unit_number is not null;
create index property_units_property_idx on public.property_units (property_id);
create index property_units_owner_idx on public.property_units (owner_id);
create index property_units_search_idx on public.property_units (bedrooms, bathrooms, area_sqm);
create trigger property_units_updated_at before update on public.property_units
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- listings
create table public.listings (
  id uuid primary key default gen_random_uuid(),
  unit_id uuid not null references public.property_units (id) on delete restrict,
  owner_id uuid not null references public.profiles (id) on delete restrict,
  category_id integer not null references public.categories (id) on delete restrict,
  purpose public.listing_purpose not null,
  status public.listing_status not null default 'draft',
  title text not null check (char_length(title) between 5 and 200),
  description text not null check (char_length(description) between 20 and 10000),
  -- Whole baht; see docs/architecture.md (A3).
  sale_price bigint check (sale_price > 0 and sale_price <= 100000000000),
  monthly_rent bigint check (monthly_rent > 0 and monthly_rent <= 100000000),
  daily_rent bigint check (daily_rent > 0 and daily_rent <= 10000000),
  -- Single sortable price so keyset pagination can use one index across purposes.
  price_sort bigint generated always as (coalesce(sale_price, monthly_rent, daily_rent)) stored,
  deposit bigint check (deposit >= 0),
  booking_fee bigint check (booking_fee >= 0),
  additional_terms text check (char_length(additional_terms) <= 5000),
  rental_terms text check (char_length(rental_terms) <= 5000),
  min_lease_months smallint check (min_lease_months between 1 and 120),
  pet_policy public.pet_policy not null default 'not_allowed',
  available_from date,
  contact_name text not null check (char_length(contact_name) between 1 and 100),
  contact_phone text check (contact_phone ~ '^\+?[0-9]{9,15}$'),
  contact_line text check (char_length(contact_line) <= 50),
  video_url text check (video_url ~ '^https://'),
  virtual_tour_url text check (virtual_tour_url ~ '^https://'),
  search_text text not null default '',
  published_at timestamptz,
  expires_at timestamptz,
  reviewed_by uuid references public.profiles (id) on delete set null,
  reviewed_at timestamptz,
  rejected_reason text check (char_length(rejected_reason) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Sale and rent keep separate pricing.
  constraint listings_price_matches_purpose check (
    (purpose = 'sale' and sale_price is not null and monthly_rent is null and daily_rent is null)
    or (purpose = 'rent' and sale_price is null and (monthly_rent is not null or daily_rent is not null))
  )
);
create index listings_unit_idx on public.listings (unit_id);
create index listings_owner_idx on public.listings (owner_id, status);
create index listings_category_idx on public.listings (category_id);
create index listings_reviewed_by_idx on public.listings (reviewed_by);
create index listings_status_created_idx on public.listings (status, created_at desc);
create index listings_expiry_idx on public.listings (expires_at) where status = 'published';
create index listings_published_recent_idx on public.listings (published_at desc, id desc) where status = 'published';
create index listings_price_sort_idx on public.listings (price_sort, id) where status = 'published';
create index listings_search_trgm_idx on public.listings using gin (search_text extensions.gin_trgm_ops);
-- Duplicate protection: one live listing per unit and purpose, and no repeated titles per owner.
create unique index listings_one_active_per_unit_key on public.listings (unit_id, purpose)
  where status in ('pending_review', 'published', 'paused');
create unique index listings_no_duplicate_title_key on public.listings (owner_id, purpose, lower(title))
  where status in ('pending_review', 'published', 'paused');
create trigger listings_updated_at before update on public.listings
  for each row execute function public.set_updated_at();

